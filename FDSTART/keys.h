/*
 * KEYS.H - FastDoom text mode launcher, keyboard scan codes
 */

#ifndef KEYS_H
#define KEYS_H

/* Scan codes of the arrow and navigation keys: the second byte of
   an extended key returned by getch(). */
#define KEY_UP    72
#define KEY_DOWN  80
#define KEY_LEFT  75
#define KEY_RIGHT 77
#define KEY_PGUP  73
#define KEY_PGDN  81
#define KEY_HOME  71
#define KEY_END   79

#endif /* KEYS_H */
